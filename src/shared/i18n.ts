const messages: Record<AppLanguage, Record<string, string>> = {
  'zh-CN': { ...zhCN, ...improvementZh },
  'en-US': { ...enUS, ...improvementEn }
}

export function translate(language: AppLanguage, key: string, variables: Variables = {}): string {
  const template = messages[language][key] ?? enUS[key] ?? key
  return template.replace(/\{(\w+)\}/g, (_match, name: string) =>
    String(variables[name] ?? `{${name}}`)
  )
}
